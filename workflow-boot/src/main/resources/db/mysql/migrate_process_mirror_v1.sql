CREATE TABLE IF NOT EXISTS `t_process_instance_mirror` (
  `process_instance_id` varchar(64) NOT NULL,
  `root_process_instance_id` varchar(64),
  `parent_process_instance_id` varchar(64),
  `process_definition_id` varchar(128) NOT NULL,
  `process_definition_key` varchar(64) NOT NULL,
  `process_definition_version` int,
  `process_name` varchar(255),
  `business_key` varchar(128),
  `tenant_id` varchar(64),
  `process_status` varchar(20) NOT NULL,
  `active_task_count` int NOT NULL DEFAULT 0,
  `current_node_names` varchar(1000),
  `current_handler_names` varchar(1000),
  `start_user_id` varchar(64),
  `start_user_name` varchar(255),
  `start_time` datetime,
  `end_time` datetime,
  `last_event_time` datetime,
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`process_instance_id`),
  KEY `idx_pi_business` (`business_key`, `process_status`),
  KEY `idx_pi_tenant_biz` (`tenant_id`, `business_key`),
  KEY `idx_pi_status_time` (`process_status`, `update_time`),
  KEY `idx_pi_start_user` (`start_user_id`, `start_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `t_process_task_mirror` (
  `task_id` varchar(64) NOT NULL,
  `process_instance_id` varchar(64) NOT NULL,
  `process_definition_key` varchar(64) NOT NULL,
  `business_key` varchar(128),
  `tenant_id` varchar(64),
  `activity_id` varchar(64),
  `node_name` varchar(255),
  `task_name` varchar(255),
  `task_status` varchar(20) NOT NULL,
  `task_kind` varchar(20),
  `assignee_id` varchar(64),
  `assignee_name` varchar(255),
  `owner_id` varchar(64),
  `owner_name` varchar(255),
  `candidate_user_ids` varchar(1000),
  `candidate_user_names` varchar(1000),
  `candidate_group_ids` varchar(1000),
  `candidate_group_names` varchar(1000),
  `sign_group_id` varchar(64),
  `sign_round` int,
  `sign_order` int,
  `completion_policy` varchar(32),
  `vote` varchar(20),
  `task_create_time` datetime,
  `claim_time` datetime,
  `due_time` datetime,
  `complete_time` datetime,
  `duration_ms` bigint,
  `last_event_time` datetime,
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`task_id`),
  KEY `idx_pt_process_status` (`process_instance_id`, `task_status`),
  KEY `idx_pt_business_status` (`business_key`, `task_status`),
  KEY `idx_pt_assignee_due` (`assignee_id`, `task_status`, `due_time`),
  KEY `idx_pt_sign_group` (`sign_group_id`, `task_status`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `t_process_activity_log` (
  `event_id` varchar(64) NOT NULL,
  `event_scope` varchar(16) NOT NULL,
  `event_type` varchar(32) NOT NULL,
  `process_instance_id` varchar(64) NOT NULL,
  `process_definition_key` varchar(64),
  `process_name` varchar(255),
  `business_key` varchar(128),
  `tenant_id` varchar(64),
  `task_id` varchar(64),
  `activity_id` varchar(64),
  `node_name` varchar(255),
  `actor_id` varchar(64),
  `actor_name` varchar(255),
  `from_assignee_id` varchar(64),
  `from_assignee_name` varchar(255),
  `to_assignee_id` varchar(64),
  `to_assignee_name` varchar(255),
  `opinion` varchar(2000),
  `event_time` datetime NOT NULL,
  `task_create_time` datetime,
  `duration_ms` bigint,
  `related_task_id` varchar(64),
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (`event_id`),
  KEY `idx_pa_process_time` (`process_instance_id`, `event_time`),
  KEY `idx_pa_business_time` (`business_key`, `event_time`),
  KEY `idx_pa_task_time` (`task_id`, `event_time`),
  KEY `idx_pa_actor_time` (`actor_id`, `event_time`),
  KEY `idx_pa_type_time` (`event_type`, `event_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

