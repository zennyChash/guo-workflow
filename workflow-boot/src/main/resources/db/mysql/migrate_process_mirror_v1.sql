CREATE TABLE IF NOT EXISTS `t_process_definition_catalog` (
  `process_definition_id` varchar(128) NOT NULL,
  `tenant_id` varchar(64),
  `process_key` varchar(64) NOT NULL,
  `version_number` int NOT NULL,
  `process_name` varchar(255),
  `deployment_id` varchar(128),
  `source_xml` longtext,
  `semantic_json` longtext,
  `status` varchar(20) NOT NULL DEFAULT 'PUBLISHED',
  `published_time` datetime,
  `create_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `update_time` datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`process_definition_id`),
  KEY `idx_pdc_tenant_key` (`tenant_id`, `process_key`, `version_number`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

