package com.guo.workflow.repository;

import com.guo.workflow.contract.ActionTriggerScope;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.stereotype.Repository;

import java.sql.Clob;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.List;
import java.util.Optional;

@Repository
public class ActionConfigRepository {

    private static final String SELECT_SQL = """
            SELECT id, process_definition_key, process_definition_id, activity_id,
                   trigger_scope, event, action_xml, version, enabled, remark
            FROM t_node_action_config
            WHERE process_definition_key = ?
              AND process_definition_id = ?
              AND activity_id = ?
              AND trigger_scope = ?
              AND event = ?
              AND enabled = 1
            """;
    private static final String SELECT_LEGACY_SQL = """
            SELECT id, process_definition_key, process_definition_id, activity_id,
                   trigger_scope, event, action_xml, version, enabled, remark
            FROM t_node_action_config
            WHERE process_definition_key = ?
              AND process_definition_id IS NULL
              AND activity_id = ?
              AND trigger_scope = ?
              AND event = ?
              AND enabled = 1
            """;
    private static final String UPDATE_GENERATED_SQL = """
            UPDATE t_node_action_config
            SET action_xml = ?,
                enabled = 1,
                remark = ?,
                update_time = CURRENT_TIMESTAMP
            WHERE process_definition_id = ?
              AND activity_id = ?
              AND trigger_scope = ?
              AND event = ?
            """;
    private static final String INSERT_GENERATED_SQL = """
            INSERT INTO t_node_action_config (
                process_definition_key, process_definition_id, activity_id,
                trigger_scope, event, action_xml, version, enabled, remark,
                create_time, update_time
            ) VALUES (?, ?, ?, ?, ?, ?, 1, 1, ?,
                      CURRENT_TIMESTAMP, CURRENT_TIMESTAMP)
            """;

    private final JdbcTemplate jdbcTemplate;

    public ActionConfigRepository(JdbcTemplate jdbcTemplate) {
        this.jdbcTemplate = jdbcTemplate;
    }

    /**
     * 根据流程定义、节点和事件查询动作配置
     */
    public Optional<ActionConfig> findByNodeAndEvent(String processDefinitionKey,
                                                     String activityId,
                                                     String event) {
        return find(null, processDefinitionKey, activityId, ActionTriggerScope.TASK, event);
    }

    public Optional<ActionConfig> findByDefinitionAndScope(
            String processDefinitionId,
            String processDefinitionKey,
            String activityId,
            ActionTriggerScope triggerScope,
            String event) {
        return find(
                processDefinitionId,
                processDefinitionKey,
                activityId,
                triggerScope,
                event);
    }

    public void upsertGenerated(
            String processDefinitionKey,
            String processDefinitionId,
            String activityId,
            ActionTriggerScope triggerScope,
            String event,
            String actionXml) {
        String remark = "generated by approval compiler";
        int updated = jdbcTemplate.update(
                UPDATE_GENERATED_SQL,
                actionXml,
                remark,
                processDefinitionId,
                activityId,
                triggerScope.name(),
                event);
        if (updated == 0) {
            try {
                jdbcTemplate.update(
                        INSERT_GENERATED_SQL,
                        processDefinitionKey,
                        processDefinitionId,
                        activityId,
                        triggerScope.name(),
                        event,
                        actionXml,
                        remark);
            } catch (DuplicateKeyException ignored) {
                upsertGenerated(
                        processDefinitionKey,
                        processDefinitionId,
                        activityId,
                        triggerScope,
                        event,
                        actionXml);
            }
        }
    }

    private Optional<ActionConfig> find(
            String processDefinitionId,
            String processDefinitionKey,
            String activityId,
            ActionTriggerScope triggerScope,
            String event) {
        if (processDefinitionId != null && !processDefinitionId.isBlank()) {
            List<ActionConfig> versioned = jdbcTemplate.query(
                    SELECT_SQL,
                    ps -> {
                        ps.setString(1, processDefinitionKey);
                        ps.setString(2, processDefinitionId);
                        ps.setString(3, activityId);
                        ps.setString(4, triggerScope.name());
                        ps.setString(5, event);
                        ps.setMaxRows(1);
                    },
                    CONFIG_ROW_MAPPER);
            if (!versioned.isEmpty()) {
                return Optional.of(versioned.get(0));
            }
        }

        List<ActionConfig> legacy = jdbcTemplate.query(
                SELECT_LEGACY_SQL,
                ps -> {
                    ps.setString(1, processDefinitionKey);
                    ps.setString(2, activityId);
                    ps.setString(3, triggerScope.name());
                    ps.setString(4, event);
                    ps.setMaxRows(1);
                },
                CONFIG_ROW_MAPPER);
        return legacy.stream().findFirst();
    }

    private static final RowMapper<ActionConfig> CONFIG_ROW_MAPPER = (rs, rowNum) -> {
        try {
            return new ActionConfig(
                    rs.getLong("id"),
                    rs.getString("process_definition_key"),
                    rs.getString("process_definition_id"),
                    rs.getString("activity_id"),
                    ActionTriggerScope.fromValue(rs.getString("trigger_scope"))
                            .orElse(ActionTriggerScope.TASK),
                    rs.getString("event"),
                    readClobAsString(rs, "action_xml"),
                    rs.getInt("version"),
                    rs.getInt("enabled") == 1,
                    rs.getString("remark")
            );
        } catch (SQLException e) {
            throw new RuntimeException("映射流程动作配置失败", e);
        }
    };

    /**
     * 处理 Oracle/MySQL CLOB 读取兼容
     */
    private static String readClobAsString(ResultSet rs, String columnName) throws SQLException {
        String value = rs.getString(columnName);
        if (value != null) {
            return value;
        }
        Clob clob = rs.getClob(columnName);
        if (clob == null) {
            return null;
        }
        try {
            return clob.getSubString(1, (int) clob.length());
        } finally {
            try {
                clob.free();
            } catch (SQLException freeEx) {
            }
        }
    }

    /**
     * 配置实体（record）
     */
    public record ActionConfig(
            Long id,
            String processDefinitionKey,
            String processDefinitionId,
            String activityId,
            ActionTriggerScope triggerScope,
            String event,
            String actionXml,
            int version,
            boolean enabled,
            String remark
    ) {
    }
}
